# Задача 7
# Дана масса M в килограммах. Найти количество полных тонн (1 тонна = 1000 кг).
# Количество килограммов в одной тонне
kg_v_tone = 1000
# Блок 1: ввод числа (повторяем, пока не введут целое число)
while True:
    try:
        mass = int(input("Введите массу M в килограммах: "))
        break  # ввод корректный, выходим из цикла
    except ValueError:
        print("Ошибка: нужно ввести целое число. Попробуйте снова.")

# Блок 2: проверка и вывод результата
if mass < 0:
    print("Ошибка: масса не может быть отрицательной.")
else:
    ton = mass // kg_v_tone
    print(f"Количество полных тонн: {ton}")