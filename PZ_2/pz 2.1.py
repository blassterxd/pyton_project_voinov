# Дана масса M в килограммах. Используя операцию деления нацело, найти количество полных тонн в ней (1 тонна = 1000 кг).
# Количество килограммов в одной тонне
kg_v_tone = 1000
while True:
    try:
        # Считываем строку с клавиатуры и преобразуем её в целое число.
        mass = int(input("Введите массу M в килограммах: "))
        # Проверяем, чтобы масса не была отрицательной
        if mass < 0:
            print("Ошибка: масса не может быть отрицательной. Попробуйте снова.")
            continue  # Возвращаемся к началу цикла для повторного ввода
        # Если ввод корректный, считаем тонны, выводим ответ и завершаем цикл
        ton = mass // kg_v_tone
        print(f"Количество полных тонн: {ton}")
        break  # Выходим из цикла
    except ValueError:
        # Сюда попадаем, если введённую строку нельзя преобразовать в int
        print("Ошибка: нужно ввести целое число. Попробуйте снова.")