#Дана масса M в килограммах. Используя операцию деления нацело, найти количество полных тонн в ней (1 тонна = 1000 кг).
# Количество килограммов в одной тонне
KG_IN_TONNE = 1000
def count_full_tonnes(mass_kg: int) -> int:
    """Возвращает количество полных тонн в массе, заданной в килограммах."""
    # Оператор // делит нацело: дробная часть (неполная тонна) отбрасывается.
    # Например, 5430 // 1000 = 5
    return mass_kg // KG_IN_TONNE
def main() -> None:
    """Запрашивает массу у пользователя и выводит количество полных тонн."""
    try:
        # Считываем строку с клавиатуры и преобразуем её в целое число.
        # Если пользователь введёт не число, возникнет ValueError
        mass = int(input("Введите массу M в килограммах: "))
        # Масса не может быть отрицательной, поэтому такой ввод отклоняем
        if mass < 0:
            print("Ошибка: масса не может быть отрицательной.")
        else:
            # Вычисляем количество полных тонн и выводим результат
            tonnes = count_full_tonnes(mass)
            print(f"Количество полных тонн: {tonnes}")
    except ValueError:
        # Сюда попадаем, если введённую строку нельзя преобразовать в int
        print("Ошибка: нужно ввести целое число.")

# Запускаем main() только при прямом запуске файла,
# но не при его импорте как модуля
if __name__ == "__main__":
    main()