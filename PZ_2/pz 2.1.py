#Дана масса M в килограммах. Используя операцию деления нацело, найти количество полных тонн в ней (1 тонна = 1000 кг).
# Количество килограммов в одной тонне
kgvtone = 1000
try:
    # Считываем строку с клавиатуры и преобразуем её в целое число.
    # Если пользователь введёт не число, возникнет ValueError
    mass = int(input("Введите массу M в килограммах: "))
    # Масса не может быть отрицательной, поэтому такой ввод отклоняем
    if mass < 0:
        print("Ошибка: масса не может быть отрицательной.")
    else:
        # Оператор // делит нацело: неполная тонна отбрасывается.
        # Например, 5430 // 1000 = 5
        ton = mass // kgvtone
        print(f"Количество полных тонн: {ton}")
except ValueError:
    # Сюда попадаем, если введённую строку нельзя преобразовать в int
    print("Ошибка: нужно ввести целое число.")