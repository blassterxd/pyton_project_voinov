#Дана масса M в килограммах. Используя операцию деления нацело, найти количество полных тонн в ней (1 тонна = 1000 кг).
KG_IN_TONNE = 1000  # количество килограммов в одной тонне

def main():
    """Запрашивает массу в кг и выводит количество полных тонн."""
    try:
        mass = int(input("Введите массу M в килограммах: "))

        if mass < 0:
            print("Ошибка: масса не может быть отрицательной.")
            return

        # Деление нацело отбрасывает неполную тонну
        tonnes = mass // KG_IN_TONNE

        print(f"Количество полных тонн: {tonnes}")
    except ValueError:
        print("Ошибка: нужно ввести целое число.")


if __name__ == "__main__":
    main()