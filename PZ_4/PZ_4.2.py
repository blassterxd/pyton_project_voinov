# Лыжник в первый день пробежал 10 км, каждый следующий день увеличивает
# пробег на P процентов от пробега предыдущего дня (0 < P < 50).
# Определить, после какого дня суммарный пробег превысит 200 км,
# и вывести количество дней K и суммарный пробег S.
p = input("Введите P (0 < P < 50): ")
while type(p) != float:  # обработка исключений
    try:
        p = float(p)
        if not 0 < p < 50:
            raise ValueError
    except ValueError:
        print("Неправильно ввели!")
        p = input("Введите P (0 < P < 50): ")

run = 10.0  # пробег за текущий день
s = 10.0    # суммарный пробег
k = 1       # количество дней
while s <= 200:
    run += run * p / 100
    s += run
    k += 1

print("K =", k)
print("S =", s)
